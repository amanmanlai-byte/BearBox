(async () => {
  const checks = [], errors = []; let interval;
  window.addEventListener('error', e => errors.push(e.message));
  window.addEventListener('unhandledrejection', e => errors.push(String(e.reason)));
  const check = (v, m) => { if (!v) throw new Error(m); checks.push(m); };
  const pause = (ms = 120) => new Promise(r => setTimeout(r, ms));
  const until = async fn => { for (let i = 0; i < 80; i++) { if (fn()) return; await pause(100); } throw new Error('UI update timeout'); };
  const change = async (query, value, key, expected = value) => {
    const el = document.querySelector(query); if (!el) throw new Error('missing ' + query);
    el.value = value; el.dispatchEvent(new Event(el.type === 'range' ? 'input' : 'change', { bubbles: true }));
    await until(() => X.S.settings[key] === expected); await pause();
  };
  const nav = [...document.querySelectorAll('#nav button')];
  check(nav.findIndex(b => b.textContent === '界面自定义') + 1 === nav.findIndex(b => b.textContent === '设置'), 'appearance navigation precedes settings');
  const strip = document.querySelector('.window-drag'), side = document.querySelector('.side');
  check(strip.getBoundingClientRect().top < 40 && strip.querySelector('.window-controls').getBoundingClientRect().right > innerWidth - 25, 'window controls are in upper-right corner');
  check([...strip.querySelectorAll('button')].map(b => b.dataset.windowAction).join(',') === 'minimize,maximize,close', 'three window controls remain accessible');
  window.__go('settings');
  check(![...document.querySelectorAll('.sect h2')].some(x => x.textContent === '界面'), 'appearance section moved out of general settings');
  window.__go('appearance');
  check(document.querySelectorAll('.accent-swatch').length === 6, 'six accent presets are present');
  check(document.querySelectorAll('.appearance-page canvas').length >= 3, 'custom accent, font and surface color wheels are present');
  check(document.querySelector('[aria-label="显示模式"]').options.length === 3, 'light dark and system options are present');
  await change('[aria-label="显示模式"]', 'light', 'appearanceMode');
  await api('setSettings', { fontColor: '#ffffff', uiColor: '#eeeeee', glassEnabled: true, glassOpacity: .15 }); await pause(500);
  check(document.documentElement.dataset.fontAdjusted === 'true', 'unreadable white font is corrected in light mode');
  const field = document.createElement('input'); document.querySelector('.appearance-page').append(field);
  const rgb = getComputedStyle(field).color.match(/\d+/g).slice(0,3).map(Number);
  check(Math.max(...rgb) < 160, 'light input text is dark and readable'); field.remove();
  const cardBg = getComputedStyle(document.querySelector('.appearance-page .card')).backgroundColor;
  check(cardBg !== 'rgba(0, 0, 0, 0)', 'glass card retains a visible surface');
  await change('[aria-label="显示模式"]', 'dark', 'appearanceMode');
  check(document.documentElement.dataset.fontAdjusted === 'false', 'saved light font becomes usable again in dark mode');
  await change('[aria-label="显示模式"]', 'system', 'appearanceMode');
  const actualDark = ['dark','forest-dark'].includes(document.documentElement.dataset.theme);
  check(actualDark === matchMedia('(prefers-color-scheme: dark)').matches, 'system mode follows operating system preference');
  await change('[aria-label="字体大小"]', 'large', 'fontSize');
  check(parseFloat(getComputedStyle(document.body).fontSize) === 15, 'large font previews immediately');
  await change('[aria-label="界面密度"]', 'compact', 'uiDensity');
  check(parseFloat(getComputedStyle(document.querySelector('#nav button')).height) === 33, 'compact density previews immediately');
  await change('[aria-label="侧边栏宽度"]', '250', 'sidebarWidth', 250);
  check(Math.round(side.getBoundingClientRect().width) === 250, 'sidebar width previews immediately');
  const collapse = [...document.querySelectorAll('.appearance-layout input[type=checkbox]')][0]; collapse.checked = true; collapse.dispatchEvent(new Event('change', { bubbles: true }));
  await until(() => X.S.settings.sidebarCollapsed === true);
  check(side.classList.contains('collapsed') && side.getBoundingClientRect().width === 78, 'default collapsed sidebar is usable');
  check(document.querySelector('#side-toggle').getBoundingClientRect().width > 0, 'sidebar can be expanded after collapse');
  document.querySelector('#side-toggle').click(); await until(() => X.S.settings.sidebarCollapsed === false);
  check(side.getBoundingClientRect().width === 250, 'sidebar expands to saved width');
  check(!document.querySelector('[aria-label="界面毛玻璃模糊"]'), 'separate glass blur control removed');
  await change('[aria-label="窗口不透明度"]', '85', 'windowOpacity', .85);
  const info = await api('appInfo'); check(info.windowOpacity == null || Math.abs(info.windowOpacity - .85) < .03, 'native window opacity applies');
  document.querySelector('.accent-swatch[title="紫色"]').click(); await until(() => X.S.settings.accentColor === '#7654b7');
  check(document.documentElement.style.getPropertyValue('--accent').length > 0, 'accent preset applies');
  const custom = document.querySelector('.accent-custom input[type=text]'); custom.value = '#2f6bff'; custom.dispatchEvent(new Event('change', { bubbles: true }));
  await until(() => X.S.settings.accentColor === '#2f6bff');
  check(document.documentElement.style.getPropertyValue('--accent').length > 0, 'custom accent color applies and saves');
  document.querySelector('.accent-swatch[title="紫色"]').click(); await until(() => X.S.settings.accentColor === '#7654b7');
  await change('[aria-label="显示模式"]', 'light', 'appearanceMode');
  check(document.documentElement.dataset.fontAdjusted === 'true', 'low contrast protection re-evaluates after theme change');
  check(errors.length === 0, 'no renderer errors');
  return { passed: checks.length, checks };
})()
